import WebSocket from 'ws';
const url = 'ws://127.0.0.1:3111/ws';
const log = (...a) => console.log(...a);
const open = (name) => new Promise((res, rej) => { const ws = new WebSocket(url); ws.inbox = []; ws.on('message', m => { const d = JSON.parse(m); ws.inbox.push(d); if (!['players','hostBots'].includes(d.t)) log(`[${name}]`, d.t, d.message || d.code || d.score ? JSON.stringify(d.score||d.message||d.code) : ''); }); ws.on('open', () => res(ws)); ws.on('error', rej); });
const wait = (ws, t, ms=3000) => new Promise((res, rej) => { const i = ws.inbox.findIndex(d => d.t === t); if (i >= 0) return res(ws.inbox.splice(i,1)[0]); const h = m => { const d = JSON.parse(m); if (d.t === t) { ws.off('message', h); res(d); } }; ws.on('message', h); setTimeout(() => { ws.off('message', h); rej(new Error('timeout waiting ' + t)); }, ms); });
const send = (ws, o) => ws.send(JSON.stringify(o));
const host = await open('host'); await wait(host,'hello');
send(host, { t:'create', name:'HOST_1', team:0, settings:{ blueBots:0, redBots:0, bluePlayers:0, redPlayers:0, map:'WAREHOUSE' }, public:true });
const created = await wait(host, 'created');
log('room', created.code, 'settings', JSON.stringify(created.settings));
if (created.settings.bluePlayers !== 1) throw new Error('host slot not reserved');
const guest = await open('guest'); await wait(guest,'hello');
send(guest, { t:'join', code: created.code, name:'FRIEND', team:1 });
const err = await wait(guest, 'error'); log('expected refusal:', err.message);
send(host, { t:'roomSettings', settings:{ ...created.settings, redPlayers:1, redBots:2, blueBots:1 } });
await wait(host, 'roomUpdate');
send(guest, { t:'join', code: created.code, name:'FRIEND', team:1 });
const joined = await wait(guest, 'joined'); log('guest joined team', joined.players.find(p=>p.name==='FRIEND').team);
const rooms = await (await fetch('http://127.0.0.1:3111/api/rooms')).json(); log('api/rooms', JSON.stringify(rooms));
send(guest, { t:'chat', text:'hello' }); await wait(host, 'chat');
send(host, { t:'start' }); const started = await wait(guest, 'started'); log('started seed', started.seed, 'map', started.settings.map);
await wait(guest, 'players');
send(host, { t:'damage', to: guest.id || joined.id, dmg: 150, head:true, fromX:1, fromZ:2 });
const dmg = await wait(guest, 'damage'); log('guest hp', dmg.hp);
const kill = await wait(host, 'kill'); log('kill', kill.killerName, '->', kill.victimName, JSON.stringify(kill.score));
send(guest, { t:'respawn' }); await wait(host, 'respawned');
send(host, { t:'botKill', d:{ killerId: created.id, killerName:'HOST_1', killerTeam:0, victimName:'VIPER_12', victimTeam:1, head:false } });
const k2 = await wait(guest, 'kill'); log('bot kill score', JSON.stringify(k2.score));
send(host, { t:'matchEnd', winner:0 }); const end = await wait(guest, 'matchEnd'); log('matchEnd', end.winner, JSON.stringify(end.score), end.players.length, 'players');
await new Promise(r => setTimeout(r, 400));
const lb = await (await fetch('http://127.0.0.1:3111/api/leaderboard')).json(); log('leaderboard', JSON.stringify(lb.players));
const health = await (await fetch('http://127.0.0.1:3111/api/health')).json(); log('health', JSON.stringify(health));
const page = await (await fetch('http://127.0.0.1:3111/')).text(); log('page ok', page.includes('LOADING ERANGEL STRIKE') || page.includes('__next'));
const game = await fetch('http://127.0.0.1:3111/game/index.html'); log('game html', game.status);
const eng = await fetch('http://127.0.0.1:3111/game/engine.js'); log('engine.js', eng.status, eng.headers.get('content-length'));
const glb = await fetch('http://127.0.0.1:3111/images/soldier.glb'); log('soldier.glb', glb.status);
host.close(); guest.close();
log('ALL GOOD');
process.exit(0);
